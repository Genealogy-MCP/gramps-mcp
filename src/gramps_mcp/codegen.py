"""
Generate the resource table from the pinned OpenAPI snapshot.

Reads `schema/openapi.json` plus the handwritten maps in `resource_policy`
and emits `resource_table.py`: per entity, its paths, verbs, list filter
params and writable fields. It never touches the pydantic write models.

    python -m src.gramps_mcp.codegen          # rewrite the table
    python -m src.gramps_mcp.codegen --check  # diff only, exit 1 on drift

`--check` also runs as a unit test, so a stale or hand-edited table fails CI
without any network access.
"""

import argparse
import difflib
import hashlib
import json
import sys
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional, Tuple

from .resource_policy import (
    ENTITY_COLLECTIONS,
    ENTITY_COMPONENTS,
    PERSON_SCHEMA_FIELDS,
    READ_ONLY_FIELDS,
)
from .resource_rows import EntityResource, FieldSpec, ListParam

REPO_ROOT = Path(__file__).resolve().parents[2]
SCHEMA_DIR = REPO_ROOT / "schema"
SNAPSHOT_PATH = SCHEMA_DIR / "openapi.json"
SIDECAR_PATH = SCHEMA_DIR / "openapi.meta.json"
TABLE_PATH = Path(__file__).with_name("resource_table.py")

GENERATED_MARKER = "# Generated by `python -m src.gramps_mcp.codegen`. Do not edit."
# The repo forbids source files of 500 lines or more; refuse well before
# that so the split happens as a deliberate change, not a hook failure.
MAX_TABLE_LINES = 450

PERSON_SCHEMA_SOURCE = (
    "https://github.com/gramps-project/gramps-web-api/blob/v{version}"
    "/gramps_webapi/api/resources/schemas.py"
)
ATTRIBUTION = (
    "The snapshot is the OpenAPI document served by gramps-web-api "
    "(https://github.com/gramps-project/gramps-web-api), copyright the "
    "Gramps Web API contributors, licensed AGPL-3.0."
)

COLLECTION_VERBS = ("GET", "POST")
ITEM_VERBS = ("GET", "PUT", "DELETE")


class CodegenError(Exception):
    """The snapshot or the policy maps do not describe the entity."""


def load_snapshot(path: Path = SNAPSHOT_PATH) -> Dict[str, Any]:
    """Read the checked-in OpenAPI snapshot."""
    return json.loads(path.read_text(encoding="utf-8"))


def load_sidecar(path: Path = SIDECAR_PATH) -> Dict[str, Any]:
    """Read the sidecar that records where the snapshot came from."""
    return json.loads(path.read_text(encoding="utf-8"))


def _render_type(schema: Dict[str, Any]) -> str:
    """Compact rendering of an OpenAPI property schema (see FieldSpec)."""
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    all_of = schema.get("allOf")
    if isinstance(all_of, list) and len(all_of) == 1:
        return _render_type(all_of[0])
    type_name = schema.get("type")
    if type_name == "array":
        items = schema.get("items")
        return f"array[{_render_type(items)}]" if items else "array"
    if isinstance(type_name, str):
        return type_name
    return "any"


def _list_params(spec: Dict[str, Any], collection: str) -> Tuple[ListParam, ...]:
    """Query parameters of the collection GET, in spec order."""
    operation = spec["paths"][f"/api/{collection}"].get("get", {})
    return tuple(
        ListParam(param["name"], _render_type(param.get("schema", {})))
        for param in operation.get("parameters", [])
        if param.get("in", "query") == "query"
    )


def _person_fields(component: Optional[Dict[str, Any]]) -> Tuple[FieldSpec, ...]:
    """Person fields from upstream PersonSchema, checked against the component.

    The 3.16 document registers a Person component; older ones did not.
    Either way the handwritten list is the source, and a registered
    component that disagrees with it means PersonSchema changed upstream.
    """
    if component is None:
        return tuple(
            FieldSpec(name, "any")
            for name in PERSON_SCHEMA_FIELDS
            if name not in READ_ONLY_FIELDS
        )
    properties = component.get("properties", {})
    unexpected = sorted(set(properties) - set(PERSON_SCHEMA_FIELDS))
    missing = sorted(set(PERSON_SCHEMA_FIELDS) - set(properties))
    if unexpected or missing:
        raise CodegenError(
            "Person component disagrees with PERSON_SCHEMA_FIELDS: "
            f"not in policy list {unexpected}, not in component {missing}. "
            "Update resource_policy.PERSON_SCHEMA_FIELDS from upstream "
            "PersonSchema at the pinned version."
        )
    return _component_fields(properties)


def _component_fields(properties: Dict[str, Any]) -> Tuple[FieldSpec, ...]:
    """Writable fields of a component: every property not server-computed."""
    return tuple(
        FieldSpec(name, _render_type(schema))
        for name, schema in properties.items()
        if name not in READ_ONLY_FIELDS
    )


def build_rows(
    spec: Dict[str, Any],
    entities: Iterable[str] = tuple(ENTITY_COMPONENTS),
) -> Dict[str, EntityResource]:
    """Build one EntityResource per entity from the spec and the policy maps.

    Args:
        spec: Parsed OpenAPI 3 document as gramps-webapi serves it.
        entities: Entity names to include, in output order.

    Returns:
        Entity name to its resource row.

    Raises:
        CodegenError: A path or component the policy names is absent from
            the spec, or the Person component disagrees with the policy list.
    """
    components = spec.get("components", {}).get("schemas", {})
    paths = spec.get("paths", {})
    rows: Dict[str, EntityResource] = {}
    for entity in entities:
        collection = ENTITY_COLLECTIONS[entity]
        item = f"{collection}{{handle}}"
        for relative in (collection, item):
            if f"/api/{relative}" not in paths:
                raise CodegenError(f"snapshot has no path /api/{relative}")
        component_name = ENTITY_COMPONENTS[entity]
        component = components.get(component_name)
        if entity == "person":
            fields = _person_fields(component)
        elif component is None:
            raise CodegenError(f"snapshot has no component {component_name}")
        else:
            fields = _component_fields(component.get("properties", {}))
        rows[entity] = EntityResource(
            entity=entity,
            component=component_name,
            collection_path=collection,
            item_path=item,
            collection_verbs=COLLECTION_VERBS,
            item_verbs=ITEM_VERBS,
            list_params=_list_params(spec, collection),
            fields=fields,
        )
    return rows


def _render_verbs(verbs: Tuple[str, ...]) -> str:
    """Tuple literal in the double-quoted form `ruff format` leaves alone."""
    return "(" + ", ".join(f'"{verb}"' for verb in verbs) + ")"


def _render_params_block(name: str, params: Tuple[ListParam, ...]) -> List[str]:
    """Render one ListParam tuple constant as source lines."""
    lines = [f"{name} = ("]
    lines += [f'    ListParam("{p.name}", "{p.type}"),' for p in params]
    lines.append(")")
    return lines


def render(rows: Dict[str, EntityResource], version: str = "") -> str:
    """Render the rows as the source of `resource_table.py`.

    Identical list-param sets are emitted once and shared by name, which
    keeps the ten near-identical Gramps collections well under the
    repo's file-length limit.
    """
    param_sets: Dict[Tuple[ListParam, ...], str] = {}
    for row in rows.values():
        if row.list_params not in param_sets:
            param_sets[row.list_params] = f"_LIST_PARAMS_{len(param_sets)}"

    lines = [
        "# SPDX-License-Identifier: AGPL-3.0-only",
        "# Copyright (C) 2026 Federico Castagnini",
        GENERATED_MARKER,
        "",
        '"""',
        "Resource table: Gramps entities as the pinned gramps-webapi OpenAPI",
        f"snapshot describes them{f' (gramps-webapi {version})' if version else ''}.",
        "",
        "Edit `schema/openapi.json` via `make schema-fetch` or the maps in",
        "`resource_policy.py`, then rerun codegen. Never edit this file.",
        '"""',
        "",
        "from typing import Dict",
        "",
        "from .resource_rows import EntityResource, FieldSpec, ListParam",
        "",
    ]
    for params, name in param_sets.items():
        lines += _render_params_block(name, params)
        lines.append("")
    lines.append("ENTITY_RESOURCES: Dict[str, EntityResource] = {")
    for entity, row in rows.items():
        lines += [
            f'    "{entity}": EntityResource(',
            f'        entity="{row.entity}",',
            f'        component="{row.component}",',
            f'        collection_path="{row.collection_path}",',
            f'        item_path="{row.item_path}",',
            f"        collection_verbs={_render_verbs(row.collection_verbs)},",
            f"        item_verbs={_render_verbs(row.item_verbs)},",
            f"        list_params={param_sets[row.list_params]},",
            "        fields=(",
        ]
        lines += [f'            FieldSpec("{f.name}", "{f.type}"),' for f in row.fields]
        lines += ["        ),", "    ),"]
    lines.append("}")
    text = "\n".join(lines) + "\n"
    if len(lines) >= MAX_TABLE_LINES:
        raise CodegenError(
            f"generated table is {len(lines)} lines; split it before it reaches "
            f"the {MAX_TABLE_LINES}-line ceiling"
        )
    return text


def generate(spec: Optional[Dict[str, Any]] = None) -> str:
    """Render the full table from the checked-in (or given) snapshot."""
    spec = load_snapshot() if spec is None else spec
    version = str(spec.get("info", {}).get("version", ""))
    return render(build_rows(spec), version=version)


def check(table_path: Path = TABLE_PATH) -> str:
    """Diff the checked-in table against a fresh render.

    Returns:
        A unified diff, or an empty string when the table is current.
    """
    expected = generate()
    current = table_path.read_text(encoding="utf-8") if table_path.exists() else ""
    return "".join(
        difflib.unified_diff(
            current.splitlines(keepends=True),
            expected.splitlines(keepends=True),
            fromfile=str(table_path),
            tofile="codegen",
        )
    )


def build_sidecar(
    spec_bytes: bytes,
    source_url: str,
    docker_image: str,
    metadata: Dict[str, Any],
    openapi_version: str,
    fetched_on: str,
) -> Dict[str, Any]:
    """Assemble the sidecar that records the snapshot's provenance."""
    webapi_version = str(metadata["gramps_webapi"]["version"])
    return {
        "source_url": source_url,
        "docker_image": docker_image,
        "gramps_webapi_version": webapi_version,
        "gramps_version": str(metadata.get("gramps", {}).get("version", "")),
        "openapi_version": openapi_version,
        "sha256": hashlib.sha256(spec_bytes).hexdigest(),
        "fetched_on": fetched_on,
        "license": "AGPL-3.0-only",
        "attribution": ATTRIBUTION,
        "person_schema_source": PERSON_SCHEMA_SOURCE.format(version=webapi_version),
    }


def main(argv: Optional[List[str]] = None) -> int:
    """CLI entry point: write the table, or `--check` it."""
    parser = argparse.ArgumentParser(
        description="Generate or check the resource table from the schema snapshot."
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit 1 and print the diff when the table is stale",
    )
    args = parser.parse_args(argv)
    if args.check:
        drift = check()
        if drift:
            sys.stderr.write(drift)
            sys.stderr.write("resource table is stale: run `make schema-fetch`\n")
            return 1
        sys.stderr.write("resource table is current\n")
        return 0
    TABLE_PATH.write_text(generate(), encoding="utf-8")
    sys.stderr.write(f"wrote {TABLE_PATH}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
